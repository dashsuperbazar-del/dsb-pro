-- Packet orderadjust (mig 0083): staff reduce/remove order lines before hand-over; holds and totals follow exactly.
begin;
create extension if not exists pgtap with schema extensions;
select plan(13);
insert into auth.users(id) values ('e8300000-0000-0000-0000-000000000001');
create function pg_temp.act() returns void language sql as
 $$ select set_config('request.jwt.claims','{"sub":"e8300000-0000-0000-0000-000000000001","role":"authenticated"}',true) $$;
create function pg_temp.id(k text) returns uuid language sql as $$ select current_setting('e83.'||k)::uuid $$;
create function pg_temp.res(k text) returns numeric language sql as $$ select reserved from stock_current where item_id=pg_temp.id(k) $$;
create function pg_temp.rev() returns int language sql as $$ select revision from orders where id=pg_temp.id('o') $$;
set role authenticated; select pg_temp.act();
select create_tenant('E83','e83-co','E83 Shop','e83-t');
select set_config('e83.tenant',current_tenant_id()::text,false);
select set_config('e83.shop',(select id::text from shops where tenant_id=current_tenant_id() limit 1),false);
insert into items(tenant_id,name,unit1,client_id) values(current_tenant_id(),'Soap','pc','e83-a'),(current_tenant_id(),'Oil','pc','e83-b');
select set_config('e83.a',(select id::text from items where client_id='e83-a'),false);
select set_config('e83.b',(select id::text from items where client_id='e83-b'),false);
reset role;
insert into item_prices(tenant_id,item_id,shop_id,kind,unit_level,price_paise,client_id) select pg_temp.id('tenant'),id,null,'retail',1,5000,'p-'||client_id from items where client_id like 'e83-%';
insert into stock_movements(tenant_id,shop_id,item_id,source_type,source_id,qty_base,client_id) select pg_temp.id('tenant'),pg_temp.id('shop'),id,'ADJUSTMENT',gen_random_uuid(),10,'s-'||client_id from items where client_id like 'e83-%';
set role authenticated; select pg_temp.act();
select set_storefront_items(pg_temp.id('shop'),(select jsonb_agg(jsonb_build_object('itemId',id,'published',true)) from items where client_id like 'e83-%'),'e83-i');
select set_storefront_settings(pg_temp.id('shop'),'{"slug":"e83-shop","displayName":"E83","enabled":true,"deliveryEnabled":true,"deliveryFeePaise":3000}','e83-s');
reset role; set role anon;
select place_order('e83-shop','d0000000-0000-4000-8000-000000000001',repeat('8',40),'delivery',null,'{"name":"A","phone":"9876543210","address":"1 Road"}',
 jsonb_build_array(jsonb_build_object('itemId',pg_temp.id('a'),'unitLevel',1,'qty','4'),jsonb_build_object('itemId',pg_temp.id('b'),'unitLevel',1,'qty','2')));
reset role;
select set_config('e83.o',(select id::text from orders where request_id='d0000000-0000-4000-8000-000000000001'),false);
set role authenticated; select pg_temp.act();
select throws_like($$ select adjust_order(pg_temp.id('o'),1,'[{"lineNo":1,"qty":"5"}]','x') $$,'%only be reduced%','a line can never go up');
select throws_like($$ select adjust_order(pg_temp.id('o'),1,'[{"lineNo":1,"qty":"3"}]','') $$,'%reason%','a reason is required');
select throws_like($$ select adjust_order(pg_temp.id('o'),1,'[{"lineNo":1,"qty":"0"},{"lineNo":2,"qty":"0"}]','x') $$,'%cancel the order%','removing every line is refused');
select is(adjust_order(pg_temp.id('o'),1,'[{"lineNo":1,"qty":"1"}]','Customer agreed on phone')->>'totalPaise','18000','4→1 soap: 1×₹50 + 2×₹50 + fee ₹30');
select is(pg_temp.res('a'),1::numeric,'the soap hold shrank to 1');
select is(adjust_order(pg_temp.id('o'),2,'[{"lineNo":2,"qty":"0"}]','Oil out of stock')->>'totalPaise','8000','oil removed: 1×50 + fee 30');
select is(pg_temp.res('b'),0::numeric,'the oil hold is released');
select is((select release_reason from stock_reservations sr join order_items oi on oi.id=sr.order_item_id where oi.order_id=pg_temp.id('o') and oi.line_no=2),'ADJUSTED','released as ADJUSTED');
reset role;
select set_config('e83.ref',(select public_ref from orders where id=pg_temp.id('o')),false);
select throws_like($$ update order_items set qty=99 where order_id=pg_temp.id('o') $$,'%adjust_order%','order lines cannot be edited directly');
set role anon;
select is(jsonb_array_length(public_order_status(current_setting('e83.ref'),repeat('8',40))->'items'),1,'the customer sees only the remaining line');
reset role; set role authenticated; select pg_temp.act();
select set_order_status(pg_temp.id('o'),'CONFIRMED',3); select set_order_status(pg_temp.id('o'),'PREPARING',4); select set_order_status(pg_temp.id('o'),'READY',5);
select is(fulfil_order(pg_temp.id('o'),6,'[{"mode":"cash","amount_paise":8000}]')->>'status','DELIVERED','hand-over sells only what is left');
select is((select count(*)::int from sale_invoice_items where sale_invoice_id=(select sale_invoice_id from orders where id=pg_temp.id('o'))),1,'the sale has one line');
select is((select reserved from stock_current where item_id=pg_temp.id('a'))+(select reserved from stock_current where item_id=pg_temp.id('b')),0::numeric,'nothing stays held');
reset role;
select * from finish();
rollback;
